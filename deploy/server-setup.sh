#!/usr/bin/env bash
# One-time setup of a fresh Ubuntu 24.04 server (Oracle Ampere A1) for memesforlaughs.com.
# Run as the default "ubuntu" user:  bash server-setup.sh
# Safe to run again: every step checks whether it is already done.
set -euo pipefail

echo "== Docker"
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
fi

echo "== Folders"
sudo mkdir -p /srv/memesforlaughs /data/postgres \
  /data/memecreator/templates /data/memecreator/meme-storage /data/memecreator/output \
  /data/memecreator/private /data/memecreator/db
sudo chown "$USER":"$USER" /srv/memesforlaughs
sudo chown -R 10001:10001 /data/memecreator      # the "meme" user inside the memecreator container

echo "== Code"
cd /srv/memesforlaughs
[ -d memecreator ]    || git clone https://github.com/HamidCodeHub/memecreator.git
[ -d memecreator-fe ] || git clone https://github.com/HamidCodeHub/memecreator-fe.git
if [ ! -d aiproxy ]; then
  # Private repository: read-only deploy key in ~/.ssh/aiproxy_deploy (see deploy/README.md)
  GIT_SSH_COMMAND="ssh -i $HOME/.ssh/aiproxy_deploy -o IdentitiesOnly=yes -o StrictHostKeyChecking=accept-new" \
    git clone git@github.com:HamidCodeHub/aiproxy.git
  git -C aiproxy config core.sshCommand "ssh -i $HOME/.ssh/aiproxy_deploy -o IdentitiesOnly=yes"
fi

echo "== Secrets"
cd /srv/memesforlaughs/memecreator/deploy
if [ ! -f .env ]; then
  umask 077
  cat > .env <<EOF
# Generated by server-setup.sh on $(date -u +%F). Keep a copy in your password manager.
POSTGRES_PASSWORD=$(openssl rand -hex 24)
AIPROXY_MASTER_KEY=$(openssl rand -base64 32)
AIPROXY_BOOTSTRAP_ADMIN_KEY=aip_$(openssl rand -hex 24)
AIPROXY_APP_KEY=aip_$(openssl rand -hex 24)

# Fill these in:
GEMINI_API_KEY=
GROQ_API_KEY=
CLOUDFLARE_TUNNEL_TOKEN=
EOF
  echo "Created deploy/.env - add GEMINI_API_KEY, GROQ_API_KEY and CLOUDFLARE_TUNNEL_TOKEN"
fi
[ -f memecreator.env ] || (umask 077 && cp memecreator.env.example memecreator.env)

echo "Done. Log out and back in (docker group), fill in the two env files, then: docker compose up -d --build"
