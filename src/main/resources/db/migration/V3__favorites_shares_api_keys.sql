-- Where a meme set was made: in the web app or through a personal API key (the API has a daily quota).
alter table meme_set add column source varchar(10) default 'WEB' not null;
create index ix_meme_set_quota on meme_set (account_id, source, created_at);

-- Memes a person marked with the heart. The image stays in meme.output-dir/<folder>/<file>.
create table favorite (
    id         bigint generated by default as identity primary key,
    account_id bigint        not null references user_account (id) on delete cascade,
    folder     varchar(300)  not null,
    file       varchar(200)  not null,
    template   varchar(200)  not null,
    caption    varchar(1000),                     -- the meme's texts, one per line (alt text)
    created_at timestamp with time zone not null,
    constraint uq_favorite unique (account_id, folder, file)
);

-- Memes a person chose to share: anyone with the link (/s/<token>) can see the image.
create table shared_meme (
    token      varchar(32)   primary key,         -- random, unguessable
    account_id bigint        not null references user_account (id) on delete cascade,
    folder     varchar(300)  not null,
    file       varchar(200)  not null,
    template   varchar(200)  not null,
    caption    varchar(1000),
    created_at timestamp with time zone not null,
    constraint uq_shared_meme unique (account_id, folder, file)
);

-- Personal API keys (X-API-Key: mcu_...). Only a SHA-256 hash of the key is stored.
create table user_api_key (
    id           bigint generated by default as identity primary key,
    account_id   bigint       not null references user_account (id) on delete cascade,
    key_hash     varchar(64)  not null unique,
    prefix       varchar(16)  not null,           -- first characters, so people can tell their keys apart
    name         varchar(60)  not null,
    created_at   timestamp with time zone not null,
    last_used_at timestamp with time zone
);

create index ix_user_api_key_account on user_api_key (account_id);
