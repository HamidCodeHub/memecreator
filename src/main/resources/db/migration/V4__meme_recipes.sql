-- Each meme's "recipe", so its words can be edited later: the template (or the uploaded photo's caption style)
-- and the texts. An edit is saved as a new meme (a new file next to the original); ai_* keep the AI's version.
create table meme (
    id          bigint generated by default as identity primary key,
    account_id  bigint        not null references user_account (id) on delete cascade,
    folder      varchar(300)  not null,
    file        varchar(200)  not null,
    kind        varchar(10)   not null,            -- TEMPLATE or PHOTO
    template    varchar(200),                      -- TEMPLATE: the template's name
    photo_style varchar(20),                       -- PHOTO: TOP_BOTTOM, TOP, BOTTOM or CAPTION_BAR
    texts       varchar(4000) not null,            -- JSON array
    ai_texts    varchar(4000) not null,            -- JSON array: what the AI wrote
    ai_file     varchar(200)  not null,            -- the AI's version of this meme
    created_at  timestamp with time zone not null,
    constraint uq_meme unique (account_id, folder, file)
);
