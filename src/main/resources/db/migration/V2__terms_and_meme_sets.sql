-- Which version of the Terms of use / Privacy policy each account accepted, and when (GDPR: proof of consent).
alter table user_account add column terms_version varchar(40);
alter table user_account add column terms_accepted_at timestamp with time zone;

-- Meme sets made in the web app, so an account's memes can be listed and deleted with the account.
create table meme_set (
    id         bigint generated by default as identity primary key,
    account_id bigint        not null references user_account (id) on delete cascade,
    folder     varchar(300)  not null,           -- folder name inside meme.output-dir
    topic      varchar(300)  not null,
    created_at timestamp with time zone not null
);

create index ix_meme_set_account on meme_set (account_id);
