-- People who use the web app. One account can have several ways in: a password and/or Google/Facebook.
create table user_account (
    id             bigint generated by default as identity primary key,
    email          varchar(320) unique,          -- lower-case; null when a provider shared no confirmed email
    display_name   varchar(120),
    password_hash  varchar(100),                 -- null for Google/Facebook-only accounts
    email_verified boolean      not null default false,
    plan           varchar(20)  not null default 'FREE',
    created_at     timestamp with time zone not null
);

-- A Google or Facebook sign-in linked to an account ("google" + the Google user id).
create table login_identity (
    id         bigint generated by default as identity primary key,
    provider   varchar(20)  not null,
    subject    varchar(200) not null,
    account_id bigint       not null references user_account (id) on delete cascade,
    created_at timestamp with time zone not null,
    constraint uq_login_identity unique (provider, subject)
);

-- One-time links sent by email. Only a SHA-256 hash of the token is stored.
create table email_token (
    token_hash varchar(64) primary key,
    account_id bigint      not null references user_account (id) on delete cascade,
    purpose    varchar(10) not null,              -- VERIFY or RESET
    expires_at timestamp with time zone not null,
    used_at    timestamp with time zone
);

create index ix_email_token_account on email_token (account_id, purpose);
